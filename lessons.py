def track_by_id(track_id: str) -> Track | None:
    for track in TRACKS:
        if track.id == track_id:
            return track
    return None


def lesson_by_id(lesson_id: str) -> Lesson | None:
    for track in TRACKS:
        for lesson in track.lessons:
            if lesson.id == lesson_id:
                return lesson
    return None


def track_for_lesson(lesson_id: str) -> Track | None:
    for track in TRACKS:
        if any(lesson.id == lesson_id for lesson in track.lessons):
            return track
    return None


