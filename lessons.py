"""Curriculum model and US-English tracks (Básico → Fluência)."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Example:
    en: str
    pt: str


@dataclass(frozen=True)
class Theory:
    title: str
    subtitle: str
    conceito: str
    cultura: str
    exemplos: tuple[Example, ...]

    def visible_english(self) -> str:
        parts = [item.en for item in self.exemplos if item.en]
        return " ".join(parts)

    def visible_card_text(self) -> str:
        lines = [self.title, self.subtitle, "1. Conceito", self.conceito, "2. Cultura", self.cultura, "3. Exemplos"]
        for item in self.exemplos:
            lines.append(item.en)
            lines.append(item.pt)
        return "\n".join(part for part in lines if part)


@dataclass(frozen=True)
class Exercise:
    id: str
    kind: str
    prompt_pt: str
    listen_en: str
    choices: tuple[str, ...] = ()
    answer: str = ""
    explain_correct: str = ""
    explain_wrong: str = ""
    choice_en: tuple[str | None, ...] = ()

    def english_phrases(self) -> list[str]:
        phrases = []
        if self.listen_en:
            phrases.append(self.listen_en)
        for text in self.choice_en:
            if text:
                phrases.append(text)
        return phrases


@dataclass(frozen=True)
class Lesson:
    id: str
    title: str
    blurb: str
    kind: str
    xp_bonus: int
    theory: Theory
    exercises: tuple[Exercise, ...]


@dataclass(frozen=True)
class Track:
    id: str
    title: str
    subtitle: str
    lessons: tuple[Lesson, ...]


def _ex(
    eid: str,
    prompt_pt: str,
    listen_en: str,
    choices: list[str],
    answer: str,
    explain_correct: str,
    explain_wrong: str,
    kind: str = "choice",
    choice_en: list[str | None] | None = None,
) -> Exercise:
    en_tuple: tuple[str | None, ...]
    if choice_en is None:
        en_tuple = tuple(choice if _looks_english(choice) else None for choice in choices)
    else:
        en_tuple = tuple(choice_en)
    return Exercise(
        id=eid,
        kind=kind,
        prompt_pt=prompt_pt,
        listen_en=listen_en,
        choices=tuple(choices),
        answer=answer,
        explain_correct=explain_correct,
        explain_wrong=explain_wrong,
        choice_en=en_tuple,
    )


_EN_WORDS = {
    "is",
    "are",
    "am",
    "be",
    "in",
    "to",
    "on",
    "have",
    "used",
    "flying",
    "probably",
    "return",
    "change",
    "sitting",
    "gotta",
    "gonna",
    "wanna",
    "kinda",
    "my",
    "stay",
}


def _looks_english(text: str) -> bool:
    lowered = text.lower().strip()
    if any(ch in text for ch in "áéíóúãõâêôçÁÉÍÓÚ"):
        return False
    if lowered in _EN_WORDS:
        return True
    markers = (
        "i ",
        "you ",
        "we ",
        "it's",
        "that's",
        "gonna",
        "wanna",
        "i'm",
        "i’ll",
        "i'll",
        "the ",
        "what",
        "how",
        "hey",
        "yeah",
        "let's",
        "gimme",
        "lemme",
        "don't",
        "can't",
        "won't",
        "isn't",
        "whatcha",
        "didja",
        "dunno",
        "outta",
        "kinda ",
        "for real",
        "no cap",
        "on it",
        "my bad",
    )
    return any(token in lowered for token in markers)


def _th(title: str, subtitle: str, conceito: str, cultura: str, exemplos: list[tuple[str, str]]) -> Theory:
    return Theory(
        title=title,
        subtitle=subtitle,
        conceito=conceito,
        cultura=cultura,
        exemplos=tuple(Example(en=en, pt=pt) for en, pt in exemplos),
    )


def _lesson(lid: str, title: str, blurb: str, theory: Theory, exercises: list[Exercise], kind: str = "lesson", xp: int = 25) -> Lesson:
    return Lesson(id=lid, title=title, blurb=blurb, kind=kind, xp_bonus=xp, theory=theory, exercises=tuple(exercises))


