def all_exercises() -> list[Exercise]:
    items: list[Exercise] = list(PLACEMENT)
    for track in TRACKS:
        for lesson in track.lessons:
            items.extend(lesson.exercises)
    return items


def all_examples() -> list[Example]:
    items: list[Example] = []
    for track in TRACKS:
        for lesson in track.lessons:
            items.extend(lesson.theory.exemplos)
    return items


def validate_curriculum() -> None:
    if not TRACKS:
        raise RuntimeError("Currículo vazio.")
    seen: set[str] = set()
    for exercise in all_exercises():
        if not exercise.listen_en.strip():
            raise RuntimeError(f"Exercício {exercise.id} sem frase em inglês para TTS.")
        if not exercise.id or exercise.id in seen:
            raise RuntimeError(f"ID de exercício inválido ou repetido: {exercise.id}")
        seen.add(exercise.id)
        if exercise.kind == "choice" and exercise.answer not in exercise.choices:
            raise RuntimeError(f"Resposta de {exercise.id} não está nas alternativas.")
        if exercise.kind == "fill" and not exercise.answer.strip():
            raise RuntimeError(f"Fill {exercise.id} sem gabarito.")
    for example in all_examples():
        if not example.en.strip():
            raise RuntimeError("Exemplo de teoria sem inglês.")
        if not example.pt.strip():
            raise RuntimeError("Exemplo de teoria sem tradução.")

